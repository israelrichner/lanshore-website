/**
 * Heading-outline gate over the prerendered HTML.
 *
 * Reads what the build actually emitted rather than the JSX that produced it,
 * because the bug this exists to catch is a DOM-order bug: on the three demo
 * pages the page-level h2 was written *below* the demo component in the JSX,
 * so the source read h1 then h2 then h3 while the rendered document read
 * h1 then h3 then h2. Only the output tells the truth.
 *
 * Three rules, all of them things a screen reader and an answer engine both
 * care about:
 *
 *   H1 — exactly one <h1> per page.
 *   H2 — the first heading on the page is that <h1>.
 *   H3 — no descent step greater than +1 (h2 to h4 is a skipped level;
 *        h4 back up to h2 is fine, closing a section is not a skip).
 *
 * Run after `npm run build`. Reads no network and no browser.
 */

import fs from "node:fs";
import { walkHtml, routeOf, requireBuild } from "./lib/build-output.mjs";

/* Headings inside these containers are UI chrome in a widget, not document
   structure. Empty today and deliberately so: the fix for a skipped level is
   a real heading, not an exemption. Kept as the documented escape hatch so the
   next person adds a reasoned entry instead of deleting the check. */
const EXEMPT_ROUTES = new Set();

/**
 * Headings in document order.
 *
 * A regex rather than a DOM parse: the markup is generated by React, so the
 * tags are well-formed and never nested inside each other, which is the case
 * that would actually require a parser. Matches the opening tag only.
 */
function headings(html) {
  const found = [];
  const re = /<h([1-6])(?=[\s>])/gi;
  let m;
  while ((m = re.exec(html)) !== null) found.push(Number(m[1]));
  return found;
}

function checkFile(file) {
  const route = routeOf(file);
  if (EXEMPT_ROUTES.has(route)) return [];

  const levels = headings(fs.readFileSync(file, "utf8"));
  const errors = [];

  if (levels.length === 0) return errors; // a page with no headings breaks no rule here

  const h1Count = levels.filter((l) => l === 1).length;
  if (h1Count !== 1) {
    errors.push(`H1 ${route}: expected exactly one <h1>, found ${h1Count}`);
  }
  if (levels[0] !== 1) {
    errors.push(`H2 ${route}: first heading is <h${levels[0]}>, expected <h1>`);
  }
  for (let i = 1; i < levels.length; i++) {
    const step = levels[i] - levels[i - 1];
    if (step > 1) {
      errors.push(
        `H3 ${route}: skipped level — <h${levels[i - 1]}> followed by <h${levels[i]}> ` +
          `(heading ${i + 1} of ${levels.length}). Insert the missing <h${levels[i - 1] + 1}>, ` +
          `or move the existing one above the component that renders the deeper headings.`
      );
    }
  }
  return errors;
}

function main() {
  requireBuild("check:headings");

  const files = walkHtml();
  if (files.length === 0) {
    console.error("check:headings: found no prerendered HTML. The build layout changed; this gate is checking nothing.");
    process.exit(1);
  }
  const errors = files.flatMap(checkFile);

  if (errors.length) {
    console.error(`check:headings FAILED — ${errors.length} problem(s):\n`);
    for (const e of errors) console.error(`  ${e}`);
    process.exit(1);
  }
  console.log(`check:headings OK — ${files.length} prerendered routes, outlines clean`);
}

main();
